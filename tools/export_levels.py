out = []
for i, (name, tip, hint, rows, cols, placed) in enumerate(CHOSEN, 1):
    placed_t = [tuple(map(tuple, p)) for p in placed]
    lvl = seed_to_level(placed_t, rows, cols, flips=True)
    assert lvl, f"level {i} invalid"
    out.append({
        "id": i,
        "name": name,
        "tip": tip,
        "hint": hint,
        "rows": rows,
        "cols": cols,
        "clues": lvl["clues"],
        "pieces": lvl["pieces"],
        "hasSolution": True,
        "overlapCells": lvl["overlap"],
    })
    print(f"{i}. {name}: {rows}x{cols} pieces={len(placed)} clues={len(lvl['clues'])} ov={lvl['overlap']}")

json.dump(out, open("levels.json", "w", encoding="utf-8"), ensure_ascii=False, indent=2)
